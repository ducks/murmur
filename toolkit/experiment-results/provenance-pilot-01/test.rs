// Public similar_rules protocol: A=[.10,.70], B=[.30,.90], 1000 events
// per phase and frozen probe, rate .05; bootstrap seed 358_001 plus outcome
// and comparison index, 10,000 draws. Starting revision f6fd8ef214d4924e84628fa27359a5b2e1f5f47a.
// Allocation has no overlap with the two archived allocations or documented
// 96M--98M ranges; there is no complete historical seed registry.
#[test]
fn similar_rules_unguarded_no_smoothing_allocated() {
    use std::time::Instant;
    const N: usize = 100;
    const LEN: usize = 1000;
    let rules = [[0.10, 0.70], [0.30, 0.90]];
    let mut counts = [[[0usize; 3]; 3]; N];
    let mut nanos = [0u128; 3];
    let mut roles = std::collections::HashSet::new();
    for (i, &(stream, init, probe)) in CORRECTION_ALLOCATION.iter().enumerate() {
        assert!(roles.insert(stream) && roles.insert(init) && roles.insert(probe));
        let mut a = Candidate::new(init, 0.05).unguarded_smoothing();
        let mut b = a.without_smoothing();
        let mut m = Mixture::new(init, 0.05);
        let mut rng = Rng(stream);
        let mut x = (rng.next_u64() & 1) as usize;
        for t in 0..3 * LEN {
            let phase = t / LEN;
            let y = usize::from(rng.uniform() < rules[usize::from(phase == 1)][x]);
            let start = Instant::now(); let pa = a.predict(x); a.observe(x,y,true); nanos[0] += start.elapsed().as_nanos();
            let start = Instant::now(); let pb = b.predict(x); b.observe(x,y,true); nanos[1] += start.elapsed().as_nanos();
            let start = Instant::now(); let pm = m.step(x,y,true).0; nanos[2] += start.elapsed().as_nanos();
            if phase > 0 && t % LEN < 100 {
                for (k,p) in [pa,pb,pm].iter().enumerate() { counts[i][phase-1][k] += usize::from(usize::from(*p > 0.5) == y); }
            }
            x = y;
        }
        a.reset(); b.reset(); m.reset();
        let mut rng = Rng(probe);
        let mut x = (rng.next_u64() & 1) as usize;
        for _ in 0..LEN {
            let y = usize::from(rng.uniform() < rules[1][x]);
            let ps = [a.predict(x),b.predict(x),m.step(x,y,false).0];
            for (k,p) in ps.iter().enumerate() { counts[i][2][k] += usize::from(usize::from(*p > 0.5) == y); }
            a.observe(x,y,false); b.observe(x,y,false); x = y;
        }
        println!("mapping seed={i} stream={stream} init={init} probe={probe} switch_b={:?}/100 switch_a={:?}/100 recall_b={:?}/1000",counts[i][0],counts[i][1],counts[i][2]);
        println!("MURMUR_PAIRED {{\"measure\":\"similar_rules_retention_b\",\"candidate\":\"unguarded\",\"control\":\"no_smoothing\",\"seed\":{i},\"candidate_correct\":{},\"control_correct\":{},\"trials\":1000}}",counts[i][2][0],counts[i][2][1]);
    }
    println!("resources training_predict_observe_ns={nanos:?} training_steps_per_model={} inline_candidate={} inline_mixture={} peak_memory=not_measured",3*N*LEN,std::mem::size_of::<Candidate>(),std::mem::size_of::<Mixture>());
    for (w,name) in ["switch_to_b","switch_to_a","retention_b"].iter().enumerate() {
        let trials = if w == 2 { LEN } else { 100 };
        for (j,(candidate,control,a,b)) in [("unguarded","no_smoothing",0,1),("unguarded","mixture",0,2),("no_smoothing","mixture",1,2)].iter().enumerate() {
            let ca: usize = counts.iter().map(|c| c[w][*a]).sum();
            let cb: usize = counts.iter().map(|c| c[w][*b]).sum();
            let diffs: Vec<f64> = counts.iter().map(|c| (c[w][*a] as f64-c[w][*b] as f64)/trials as f64).collect();
            let mean = diffs.iter().sum::<f64>()/N as f64;
            let seed = 358_001 + (w*3+j) as u64;
            let mut rng = Rng(seed);
            let mut boot: Vec<f64> = (0..10_000).map(|_| (0..N).map(|_| diffs[(rng.next_u64()%N as u64) as usize]).sum::<f64>()/N as f64).collect();
            boot.sort_by(f64::total_cmp);
            let (lo,hi) = (boot[250],boot[9749]);
            println!("paired {name} {candidate} minus {control} mean={mean:.6} bootstrap95=[{lo:.6},{hi:.6}] draws=10000 seed={seed}");
            if w == 2 && j == 0 { println!("primary decision: {}",if lo > 0.0 {"benefit"} else if hi < 0.0 {"loss"} else {"inconclusive"}); }
            println!("MURMUR_FOLLOWUP {{\"measure\":\"similar_rules_{name}\",\"candidate\":\"{candidate}\",\"control\":\"{control}\",\"candidate_correct\":{ca},\"control_correct\":{cb},\"trials\":{}}}",N*trials);
        }
    }
}
